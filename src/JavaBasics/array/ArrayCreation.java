package JavaBasics;

public class ArrayCreation {
    public static void main(String[] args) {
        int[] arr = {1,2,3,4,5};
         for(int i=0; i<arr.length;i++){
             System.out.println(arr[i]);
         }

         String[] fruits = {"apple","mango"};
        for(int i=0; i<fruits.length;i++){
            System.out.println(fruits[i]);
        }
    }
}
